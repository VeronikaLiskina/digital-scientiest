def build_general_fallback_prompt(
    question: str,
    conversation: str | None = None,
) -> str:
    conversation_part = ""
    if conversation:
        conversation_part = (
            "Предыдущие сообщения диалога используй только для понимания текущего "
            "вопроса. Не представляй их как материалы цифрового архива.\n"
            f"{conversation}\n\n"
        )

    return (
        conversation_part
        + "В загруженных публикациях не найдено подходящих фрагментов.\n"
        "Дай краткий и полезный ответ из общих знаний. Не повторяй уведомление об "
        "отсутствии источников — оно будет добавлено программно перед ответом.\n"
        "Не придумывай публикации, ссылки, цитаты или точные сведения. Если ответ "
        "неизвестен или ненадёжен, прямо сообщи об этом.\n"
        "Отвечай на языке вопроса пользователя.\n\n"
        f"Вопрос пользователя:\n{question}\n\n"
        "Справка из общих знаний:"
    )


def build_publication_analysis_prompt(text: str, filename: str | None = None) -> str:
    safe_text = text[:7000]
    filename_part = filename or "Не указано"

    return f"""
Ты анализируешь текст, извлеченный из PDF-файла научной публикации.

Имя файла:
{filename_part}

Задача: извлечь данные для предварительного заполнения карточки публикации.

Важно:
- Данные не сохраняются автоматически в базу данных.
- Результат используется только как предварительное заполнение формы.
- Пользователь должен проверить и подтвердить данные вручную.

Используй только предоставленный текст и имя файла.

Правила:
- Не выдумывай данные.
- Если поле не найдено, верни null или пустой список.
- Не используй список литературы как источник данных о текущей публикации.
- Не используй названия журналов, сборников, конференций и организаций как название статьи.
- Если текст похож на сборник или оглавление, не извлекай данные соседних публикаций.
- Не возвращай вложенные объекты.
- Верни только JSON без пояснений.

Особое правило для title:
- Если в тексте PDF нет надежного названия статьи, не пытайся угадать его.
- Не бери в title служебные заголовки, название журнала, сборника, конференции или раздела.
- Если название надежно не найдено, верни null. Название из имени файла будет обработано отдельно программной логикой.

Особое правило для authors:
- Извлекай только авторов текущей публикации.
- Не включай авторов из списка литературы.
- Не включай редакторов, организации и учреждения.
- Если инициалы отсутствуют, не придумывай их.

Особое правило для keywords:
- Возвращай только явно указанные ключевые слова из блока "Ключевые слова" или "Keywords".
- Не придумывай ключевые слова по содержанию текста.

Формат ответа:

{{
  "authors": [],
  "title": null,
  "year": null,
  "doi": null,
  "keywords": [],
  "publication_type": null
}}

Текст публикации:
{safe_text}
"""
