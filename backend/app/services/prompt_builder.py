from sqlalchemy import null


def build_rag_context(chunks: list[dict]) -> str:
    parts: list[str] = []

    for index, chunk in enumerate(chunks, start=1):
        parts.append(
            "\n".join(
                [
                    f"[Источник {index}]",
                    f"Публикация: {chunk.get('publication_title')}",
                    f"ID публикации: {chunk.get('publication_id')}",
                    f"ID фрагмента: {chunk.get('chunk_id')}",
                    f"Сходство: {chunk.get('similarity'):.3f}",
                    "Текст фрагмента:",
                    chunk.get("text", ""),
                ]
            )
        )

    return "\n\n".join(parts)


def build_rag_prompt(question: str, context: str) -> str:
    return (
        "Ниже приведены фрагменты научных публикаций, найденные семантическим поиском.\n"
        "Используй только эти фрагменты для ответа.\n"
        "Дай содержательный ответ: сначала краткий прямой вывод, затем 2-4 предложения с деталями из найденных фрагментов.\n"
        "Если фрагменты описывают разные аспекты темы, аккуратно сопоставь их, не ограничивайся одной общей фразой.\n"
        "Отвечай на том же языке, на котором задан вопрос пользователя.\n"
        "Если вопрос задан на русском языке, отвечай только на русском.\n"
        "Если вопрос задан на английском языке, отвечай только на английском.\n"
        "Не используй китайский язык и китайские иероглифы, если вопрос не задан на китайском.\n"
        "Не смешивай языки.\n"
        "Если в найденных фрагментах недостаточно информации, прямо скажи об этом.\n\n"
        f"Контекст:\n{context}\n\n"
        f"Вопрос пользователя:\n{question}\n\n"
        "Ответ:"
    )


